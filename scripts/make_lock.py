"""Write requirements.lock: every package our direct requirements pull in, pinned to the installed version.

The `anpr` env also holds unrelated packages, so a plain `pip freeze` would over-pin; this walks the dependency
tree from requirements.txt instead. Usage: python -m scripts.make_lock
"""
import re
from importlib import metadata
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
EXTRA = ["torch", "numpy", "pydantic", "fastapi", "rapidfuzz"]  # used directly, installed before this project


def _name(req: str) -> str:
    return re.split(r"[ ;<>=!~\[]", req, maxsplit=1)[0].strip().lower()


def main() -> None:
    direct = [_name(l) for l in (ROOT / "requirements.txt").read_text().splitlines() if l.strip() and not l.startswith("#")]
    seen, todo = {}, direct + EXTRA
    while todo:
        n = todo.pop()
        if n in seen:
            continue
        try:
            dist = metadata.distribution(n)
        except metadata.PackageNotFoundError:
            continue
        seen[n] = dist.version
        for r in dist.requires or []:
            if "extra ==" not in r:
                todo.append(_name(r))
    lines = ["# Generated by python -m scripts.make_lock — pinned versions on the demo laptop (Python 3.12, anpr env).",
             "# llama-cpp-python is built from source with CUDA 13.0 for sm_120 (see DECISIONS.md)."]
    lines += [f"{n}=={v}" for n, v in sorted(seen.items())]
    (ROOT / "requirements.lock").write_text("\n".join(lines) + "\n")
    print(f"pinned {len(seen)} packages")


if __name__ == "__main__":
    main()
